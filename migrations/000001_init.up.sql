CREATE SCHEMA IF NOT EXISTS splix;

CREATE OR REPLACE FUNCTION splix.update_updated_at_column()
    RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE splix.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL DEFAULT 1,
    full_name VARCHAR(100) NOT NULL CHECK (char_length(full_name) BETWEEN 3 AND 100),
    phone_number VARCHAR(15) CHECK (
        phone_number ~ '^\+[0-9]+$'
        AND char_length(phone_number) BETWEEN 10 AND 15
    ),
    email VARCHAR(255) NOT NULL UNIQUE CHECK (char_length(email) BETWEEN 6 AND 255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

DROP TRIGGER IF EXISTS trigger_users_updated_at ON splix.users;
CREATE TRIGGER trigger_users_updated_at
    BEFORE UPDATE ON splix.users
    FOR EACH ROW
    EXECUTE FUNCTION splix.update_updated_at_column();

CREATE TABLE splix.groups (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL DEFAULT 1,
    title VARCHAR(100) NOT NULL CHECK (char_length(title) BETWEEN 1 AND 100),
    description VARCHAR(500) CHECK (char_length(description) BETWEEN 1 AND 500),
    currency CHAR(3) NOT NULL DEFAULT 'RUB',
    creator_user_id INTEGER NOT NULL REFERENCES splix.users(id) ON DELETE RESTRICT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

DROP TRIGGER IF EXISTS trigger_groups_updated_at ON splix.groups;
CREATE TRIGGER trigger_groups_updated_at
    BEFORE UPDATE ON splix.groups
    FOR EACH ROW
    EXECUTE FUNCTION splix.update_updated_at_column();

CREATE TABLE splix.expenses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL DEFAULT 1,
    description VARCHAR(200) CHECK (char_length(description) BETWEEN 1 AND 200),
    date DATE NOT NULL CHECK (date <= CURRENT_DATE),
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    split_type VARCHAR(15) NOT NULL DEFAULT 'EQUAL',
    group_id INTEGER NOT NULL REFERENCES splix.groups(id) ON DELETE CASCADE,
    payer_user_id INTEGER NOT NULL REFERENCES splix.users(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

DROP TRIGGER IF EXISTS trigger_expenses_updated_at ON splix.expenses;
CREATE TRIGGER trigger_expenses_updated_at
    BEFORE UPDATE ON splix.expenses
    FOR EACH ROW
    EXECUTE FUNCTION splix.update_updated_at_column();

CREATE TABLE splix.group_members (
    group_id INTEGER NOT NULL REFERENCES splix.groups(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES splix.users(id) ON DELETE CASCADE,
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    PRIMARY KEY (group_id, user_id)
);

CREATE TABLE splix.expense_splits (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id INTEGER NOT NULL REFERENCES splix.expenses(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES splix.users(id) ON DELETE RESTRICT,
    share NUMERIC(12, 2) NOT NULL CHECK (share > 0),
    UNIQUE (expense_id, user_id)
);

CREATE INDEX idx_group_members_user_id ON splix.group_members(user_id);
CREATE INDEX idx_expense_splits_expense_id ON splix.expense_splits(expense_id);
CREATE INDEX idx_expense_splits_user_id ON splix.expense_splits(user_id);
